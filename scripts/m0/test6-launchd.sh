#!/usr/bin/env bash
# M0 test 6 (macOS only): can a launchd job with a minimal PATH run `claude`
# and use the keychain login?
#
# Usage:
#   scripts/m0/test6-launchd.sh install     Install and start the job once.
#   scripts/m0/test6-launchd.sh result      Show the result.
#   scripts/m0/test6-launchd.sh uninstall   Remove the job and its files.
#
# The job runs `claude -p "/usage"` three times:
#   A: bare `claude` with PATH=/usr/bin:/bin:/usr/sbin:/sbin (base account)
#   B: absolute path to claude, same minimal PATH (base account)
#   C: absolute path to claude, same minimal PATH (second account)
# The log has only exit codes and yes/no results, not the usage output.
set -euo pipefail

label=dev.ccx.m0-test6
plist=$HOME/Library/LaunchAgents/$label.plist
state_dir=$HOME/.local/state/ccx-m0
job=$state_dir/test6-job.sh
log=$state_dir/test6.log
second=${CCX_M0_SECOND_ACCOUNT:-$HOME/.claude-angel2}
domain=gui/$(id -u)

[ "$(uname -s)" = Darwin ] || { echo "This test is for macOS only." >&2; exit 2; }

cmd_install() {
  local claude_bin
  claude_bin=$(command -v claude) || { echo "claude is not on PATH." >&2; exit 2; }
  mkdir -p "$state_dir" "$(dirname "$plist")"
  rm -f "$log"

  cat >"$job" <<EOF
#!/bin/bash
# Generated by scripts/m0/test6-launchd.sh. Safe to delete.
probe=\$(mktemp -d)
cd "\$probe" || exit 1
echo "date: \$(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "PATH: \$PATH"
echo "HOME set: \$([ -n "\$HOME" ] && echo yes || echo no)"
run() {
  local name=\$1; shift
  local out code limits
  out=\$(perl -e 'alarm 60; exec @ARGV' "\$@" -p "/usage" --output-format stream-json \\
    --verbose --no-session-persistence --strict-mcp-config \\
    --settings '{"disableAllHooks":true}' 2>"\$probe/err")
  code=\$?
  if printf '%s' "\$out" | grep -q '"limits":\[{'; then limits=yes; else limits=no; fi
  echo "\$name: exit=\$code limits=\$limits"
  if [ "\$limits" = no ]; then
    echo "\$name stderr (first 5 lines):"
    head -n 5 "\$probe/err" | sed 's/^/  /'
  fi
}
run "A bare claude" env -u CLAUDE_CONFIG_DIR claude
run "B absolute path" env -u CLAUDE_CONFIG_DIR "$claude_bin"
run "C absolute path, second account" env CLAUDE_CONFIG_DIR="$second" "$claude_bin"
rm -rf "\$probe"
echo done
EOF
  chmod +x "$job"

  cat >"$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array><string>/bin/bash</string><string>$job</string></array>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>/usr/bin:/bin:/usr/sbin:/sbin</string></dict>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$log</string>
  <key>StandardErrorPath</key><string>$log</string>
</dict>
</plist>
EOF

  launchctl bootout "$domain/$label" 2>/dev/null || true
  launchctl bootstrap "$domain" "$plist"
  echo "Installed and started $label."
  echo "Wait about 30 seconds, then run: scripts/m0/test6-launchd.sh result"
}

cmd_result() {
  [ -f "$log" ] || { echo "No log yet: $log" >&2; exit 1; }
  cat "$log"
  grep -q '^done$' "$log" || { echo "(The job has not finished. Try again soon.)"; exit 1; }
  echo
  if grep -q '^A bare claude: exit=0 limits=yes' "$log"; then
    echo "RESULT: PASS with PATH=/usr/bin:/bin:/usr/sbin:/sbin and bare 'claude'."
  elif grep -q '^B absolute path: exit=0 limits=yes' "$log"; then
    echo "RESULT: PASS only with the absolute path to claude. The service must"
    echo "        write the absolute path (or add its directory to PATH)."
  else
    echo "RESULT: FAIL. D4 fallback: #13 ships without launchd, and"
    echo "        stale-while-revalidate (#11) stays the primary refresh."
  fi
  grep -q '^C absolute path, second account: exit=0 limits=yes' "$log" &&
    echo "Second account: PASS." || echo "Second account: FAIL."
  echo "claude version: $(claude --version 2>/dev/null || echo unknown)"
}

cmd_uninstall() {
  launchctl bootout "$domain/$label" 2>/dev/null || true
  rm -f "$plist" "$job" "$log"
  echo "Removed $label."
}

case ${1:-} in
  install) cmd_install ;;
  result) cmd_result ;;
  uninstall) cmd_uninstall ;;
  *) sed -n '2,15p' "$0"; exit 2 ;;
esac
